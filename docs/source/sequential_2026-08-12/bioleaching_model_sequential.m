function bioleaching_model
% BIOLEACHING_MODEL  Sequential three-stage bioleaching model.
%
%   STAGE 1  culture vessel : E. coli express TetH, which is then harvested,
%                             extracted and purified.  Output = enzyme.
%   STAGE 2  conversion vessel : purified TetH + tetrathionate broth ->
%                             thiosulfate.  NO copper, NO PCB, NO gold.
%   STAGE 3  leaching vessel : thiosulfate solution + crushed PCB ->
%                             gold and copper dissolution.  NO enzyme source.
%
%   This replaces the earlier SIMULTANEOUS model in which every process ran
%   in one pot from t = 0.  The three key structural consequences are:
%
%     1. In Stage 2 the enzyme concentration [E] is a FIXED INPUT (purified
%        protein), not a state variable.  k_syn, k_deg and mu no longer
%        appear - there are no cells in the vessel.
%
%     2. Stage 2 contains no copper, so the parasitic term k1*[Cu(II)]*[S2O3]
%        and both leaching sinks vanish.  What remains is a CLOSED two-state
%        system with a conserved total (S4O6 + S2O3 = constant, since Y = 1),
%        which also has an analytical solution (integrated Michaelis-Menten).
%
%     3. In Stage 3 thiosulfate has NO source.  It is a fixed budget charged
%        at the start and depleted thereafter.  Tetrathionate regenerated by
%        the parasitic reaction accumulates as a dead-end product unless the
%        enzyme is deliberately carried over (p.carry_enzyme).
%
%   Units: umol/L (concentration), min (time), L (volume), m^2 (area),
%          umol (solid metal amounts).
%
%   Just press Run.

clc; close all;

p = default_params();

% ---------------- STAGE 1: enzyme harvest (analytical) ----------------
s1 = run_stage1(p);

% ---------------- STAGE 2: tetrathionate -> thiosulfate ----------------
[t2, Y2, aux2] = run_stage2(p);

% ---------------- STAGE 3: leaching ------------------------------------
% the Stage-2 product stream becomes the Stage-3 initial condition
S4_charge = Y2(end,1);
S2_charge = Y2(end,2);
[t3, Y3, aux3] = run_stage3(p, S4_charge, S2_charge);

% ---------------- output ------------------------------------------------
plot_stage2(t2, Y2, aux2, p);
plot_stage3(t3, Y3, aux3, p);
print_summary(s1, t2, Y2, t3, Y3, aux3, p);

%  ------------------------------------------------------------------
%  SWEEPS.  Each call re-runs BOTH stages, so a parameter that only
%  affects Stage 2 (like E2) still propagates into the Stage-3 result.
%  Comment out what you do not want.
%  ------------------------------------------------------------------
%sweep(p, 'E2',   [0.011 0.043 0.129], 'S2O3_2');      % enzyme loading, Stage 2
%sweep(p, 'k1',   [1e-6 1e-5 1e-4],    'Au_recovery'); % parasitic loss, Stage 3
%sweep(p, 'd',    [2e-3 4e-3 6e-3],    'Au_recovery'); % crush size

%sweep(p, 't2',      [1440 4320 10080],     'S2O3_2');      % Stage-2 duration
%sweep(p, 'k_cat',   [30 125 400],          'S2O3_2');      % turnover number
%sweep(p, 'k4',      [1e-5 1e-4 1e-3],      'CuII');        % Cu(I) re-oxidation
%sweep(p, 'O2',      [250 500 1000],        'Au_recovery'); % aeration
%sweep(p, 'm_Cu',    [10e-3 30e-3 60e-3],   'Au_recovery'); % copper loading

% Does carrying the enzyme into Stage 3 help?  (recycles dead-end S4O6)
compare_carryover(p);
end


%% ===================================================================
%  PARAMETERS
%  ===================================================================
function p = default_params()

% ---- operating / reactor ---------------------------------------------
p.V          = 1.0;        % L        reactor volume (both stages)
p.gold_model = 'B';        % 'A' = O2 only, 'B' = O2 + Cu(II)

% ---- STAGE 1: culture, for enzyme harvest -----------------------------
%  These describe the CULTURE vessel only.  They set how much enzyme you
%  get per litre of culture, and therefore how much culture you must grow
%  to charge Stage 2.  They do NOT appear in the Stage-2 or Stage-3 ODEs.
p.X       = 1e12;      % cell L^-1        biomass in the culture
p.k_syn   = 8.74e-17;  % umol cell^-1 min^-1  synthesis  [cascade-matched, ref 17]
p.k_deg   = 1.1e-3;    % min^-1           enzyme degradation      [ref 4]
p.mu      = 0.0173;    % min^-1           growth dilution = ln2/40min [ref 16]

% ---- STAGE 2: purified enzyme + tetrathionate broth -------------------
%  E2 is now a FREE DESIGN VARIABLE.  Purification decouples it from cell
%  density: you concentrate the harvested enzyme to whatever level you like,
%  limited only by how much culture you are willing to grow.
%     E2 = 0.043 umol/L  ->  ~96 % conversion in 3 days, ~9 L culture per L
%     E2 = 0.129 umol/L  ->  ~1 day,  ~27 L culture per L
%     E2 = 0.0048 umol/L ->  the in-situ value; would need ~27 days
p.E2      = 0.043;     % umol L^-1        purified TetH in the conversion vessel
p.t2      = 3*24*60;   % min              Stage-2 duration (3 days)
p.k_cat   = 125;       % min^-1           TetH turnover: 2.5 U/mg x 50 kDa [ref 1,2]
p.Km      = 300;       % umol L^-1        Michaelis constant, 50-2400 [ref 2]
p.Y       = 1;         % -                S2O3 per S4O6 consumed    [ref 1]

%  Tetrathionate broth charge.  The 46 g/L base powder contains 30 g/L
%  Na2S2O3.5H2O and NO tetrathionate; tetrathionate is generated in situ by
%  the iodine solution added at use (2 S2O3^2- + I2 -> S4O6^2- + 2 I-).
%  Iodine is limiting, so only part of the thiosulfate is converted:
%     30 g/L / 248.18 g/mol            = 120.88 mmol thiosulfate
%     6 g I2 / 253.81 g/mol            =  23.64 mmol iodine
%     -> 23.64 mmol S4O6, 73.60 mmol S2O3 left, in 1.02 L
p.S4_0    = 23200;     % umol L^-1        tetrathionate from broth
p.S2_0    = 72100;     % umol L^-1        residual thiosulfate from broth

% ---- STAGE 3: leaching -------------------------------------------------
p.t3      = 3*24*60;   % min              Stage-3 duration (3 days)
p.carry_enzyme = false;% logical          true = enzyme transferred with the
                       %                  liquor, so regenerated S4O6 is
                       %                  recycled back to S2O3
p.E3      = 0.043;     % umol L^-1        enzyme in Stage 3 IF carried over

% ---- solution redox ----------------------------------------------------
p.k1      = 1e-5;      % L umol^-1 min^-1  Cu(II)+S2O3 -> S4O6    [ref 6,7]
p.k3      = 1e-5;      % L umol^-1 min^-1  parasitic, = k1        [ref 6,7]
p.k4      = 1e-4;      % L umol^-1 min^-1  Cu(I) re-oxidation     [ref 7]

% ---- gold ---------------------------------------------------------------
%  Feed basis: 100 g/L PCB at 0.02 wt% Au and 30 wt% Cu -> 20 mg Au, 30 g Cu.
p.m_Au    = 20e-6;     % kg                gold on the boards (20 mg)
p.rho_Au  = 19300;     % kg m^-3                                    [doc]
p.t_film  = 0.5e-6;    % m                 plating thickness, 0.05-1 um
p.k_Au_O2 = 11.4;      % umol m^-2 min^-1  O2 route (1.9e-7 mol/m2/s) [ref 9,10]
p.k_Au_Cu = 1500;      % umol m^-2 min^-1  Cu(II) route (PCB optimum) [ref 11,12]
p.K_O2    = 50;        % umol L^-1         O2 half-saturation       [ref 10]
p.K_S     = 3900;      % umol L^-1         S2O3 half-saturation = 1/K_ads [ref 18]
p.K_Cu    = 5e4;       % umol L^-1         Cu(II) half-saturation   [ref 12]

% ---- copper -------------------------------------------------------------
p.m_Cu    = 30e-3;     % kg                copper mass (30 g)
p.rho_Cu  = 8960;      % kg m^-3                                    [doc]
p.d       = 6e-3;      % m                 crushed particle size, 2-6 mm
p.k_Cu_O2 = 200;       % umol m^-2 min^-1  O2 route (Ea ~25.8 kJ/mol) [ref 13]
p.k_Cu_Cu = 200;       % umol m^-2 min^-1  Cu(II) route (comproportionation)

% ---- oxygen --------------------------------------------------------------
p.O2      = 500;       % umol L^-1         dissolved O2, held constant

% ---- pH -------------------------------------------------------------------
%  The pH sub-model tracks ALKALINITY (net OH- added, umol/L) rather than a
%  free [H+] pool.  Tracking [H+] directly fails here: the net base production
%  is ~1e5 umol/L over the run while the free H+ pool at pH 7 is only 0.1
%  umol/L, so [H+] is driven negative and pH diverges.  Alkalinity is the
%  standard way to handle this.
%     pH = pH0 + Alk / beta      (linear buffer)
p.pH_on   = false;      % include the proton balance in Stage 3
p.beta    = 1e5;       % umol L^-1 per pH unit   buffer capacity
                       %   1e5 ~ a 0.1 M carbonate buffer.  Lower it for an
                       %   unbuffered medium and the pH swing grows.
p.pH0     = 7.0;       % -                 starting pH of the leach liquor

% ---- molar masses ---------------------------------------------------------
p.M_Au = 196.97e-3;    % kg mol^-1
p.M_Cu = 63.55e-3;     % kg mol^-1

p = refresh(p);
end


function p = refresh(p)
% Derived geometry and initial solid amounts.
p.A_Au0 = p.m_Au / (p.rho_Au * p.t_film);      % m^2, thin film (constant)
p.A_Cu0 = 6 * p.m_Cu / (p.rho_Cu * p.d);       % m^2, shrinking particle
p.nAu0  = p.m_Au / p.M_Au * 1e6;               % umol
p.nCu0  = p.m_Cu / p.M_Cu * 1e6;               % umol
end


%% ===================================================================
%  STAGE 1  -  enzyme harvest (analytical, no ODE needed)
%  ===================================================================
function s1 = run_stage1(p)
% The culture reaches steady state in ~1/(k_deg+mu) minutes, far faster than
% anything downstream, so only the steady state matters.
NA = 6.022e17;                                  % molecules per umol
s1.E_per_L   = p.k_syn * p.X / (p.k_deg + p.mu);   % umol/L of culture
s1.molec_per_cell = s1.E_per_L * NA / p.X;
s1.culture_L = p.E2 / s1.E_per_L;               % L culture per L of Stage 2
s1.mass_mg   = p.E2 * 1e-6 * 50000 * 1000;      % mg TetH per L of Stage 2
s1.tau       = 1 / (p.k_deg + p.mu);            % min, time to steady state
end


%% ===================================================================
%  STAGE 2  -  purified TetH + tetrathionate  (CLOSED SYSTEM)
%  ===================================================================
function [t, Y, aux] = run_stage2(p)
% States: y = [S4O6 ; S2O3]   both umol/L
% No copper, no PCB, no gold -> no loss terms at all.
% Conserved quantity: S4O6 + S2O3 = constant (because Y = 1).

opts = odeset('RelTol',1e-9,'AbsTol',1e-11,'NonNegative',[1 2]);
[t, Y] = ode15s(@(tt,y) rhs_stage2(tt,y,p), [0 p.t2], [p.S4_0; p.S2_0], opts);

n = numel(t);  z = zeros(n,1);
aux = struct('v_MM',z,'conv',z,'total',z);
for i = 1:n
    [~, a] = rhs_stage2(t(i), Y(i,:).', p);
    aux.v_MM(i)  = a.v_MM;
    aux.conv(i)  = 100*(1 - Y(i,1)/p.S4_0);      % % tetrathionate converted
    aux.total(i) = Y(i,1) + Y(i,2);              % conservation check
end

% Analytical completion time, integrated Michaelis-Menten:
%    Km*ln(S0/S) + (S0 - S) = Vmax*t
Vmax = p.k_cat * p.E2;
aux.t_analytical = (p.Km*log(p.S4_0/max(Y(end,1),1e-9)) + (p.S4_0 - Y(end,1))) / Vmax;
aux.Vmax = Vmax;
end


function [dy, a] = rhs_stage2(~, y, p)
S4 = max(y(1),0);
S2 = max(y(2),0);

v_MM = p.k_cat * p.E2 * S4 / (p.Km + S4);        % umol L^-1 min^-1

dS4 = -v_MM;
dS2 = +p.Y * v_MM;

dy = [dS4; dS2];
a  = struct('v_MM', v_MM);
end


%% ===================================================================
%  STAGE 3  -  leaching  (thiosulfate is a fixed budget)
%  ===================================================================
function [t, Y, aux] = run_stage3(p, S4_charge, S2_charge)
% States: y = [S4O6 ; S2O3 ; n_Au ; Au(S2O3)2 ; n_Cu ; Cu(I) ; Cu(II) ; Alk]
%             umol/L  umol/L   umol    umol/L     umol   umol/L   umol/L  umol/L
% Alk = cumulative net OH- added (alkalinity); pH = pH0 + Alk/beta

y0 = [ S4_charge ;          % 1  tetrathionate carried over from Stage 2
       S2_charge ;          % 2  thiosulfate  - the leaching budget
       p.nAu0    ;          % 3  solid gold
       0         ;          % 4  dissolved gold complex
       p.nCu0    ;          % 5  solid copper
       0         ;          % 6  Cu(I)
       0         ;          % 7  Cu(II)
       0                 ]; % 8  alkalinity, starts at zero by definition

opts = odeset('RelTol',1e-8,'AbsTol',1e-10,'NonNegative',1:7);  % Alk may be negative
[t, Y] = ode15s(@(tt,y) rhs_stage3(tt,y,p), [0 p.t3], y0, opts);

n = numel(t);  z = zeros(n,1);
aux = struct('R_Au',z,'R_Au_O2',z,'R_Au_Cu',z,'R_Cu',z,'A_Cu',z, ...
             'fS',z,'fO2',z,'fCu',z,'v3',z,'v4',z,'pH',z,'Alk',z, ...
             'Au_recovery',z,'Cu_recovery',z);
for i = 1:n
    [~, a] = rhs_stage3(t(i), Y(i,:).', p);
    aux.R_Au(i)=a.R_Au;  aux.R_Au_O2(i)=a.R_Au_O2;  aux.R_Au_Cu(i)=a.R_Au_Cu;
    aux.R_Cu(i)=a.R_Cu;  aux.A_Cu(i)=a.A_Cu;
    aux.fS(i)=a.fS;      aux.fO2(i)=a.fO2;          aux.fCu(i)=a.fCu;
    aux.v3(i)=a.v3;      aux.v4(i)=a.v4;            aux.pH(i)=a.pH;
    aux.Alk(i)=a.Alk;
end
aux.Au_recovery = 100*(1 - Y(:,3)/p.nAu0);
aux.Cu_recovery = 100*(1 - Y(:,5)/p.nCu0);
aux.S2_charge   = S2_charge;
end


function [dy, a] = rhs_stage3(~, y, p)
S4   = max(y(1),0);   S2  = max(y(2),0);
nAu  = max(y(3),0);   AuC = max(y(4),0);   %#ok<NASGU>
nCu  = max(y(5),0);   CuI = max(y(6),0);   CuII = max(y(7),0);
Alk  = y(8);          % alkalinity may be positive or negative

V  = p.V;
O2 = p.O2;
useCuII = strcmpi(p.gold_model,'B');

% ---- saturation factors (dimensionless, 0-1) ----
fO2 = O2   / (p.K_O2 + O2);
fS  = S2   / (p.K_S  + S2);
fCu = CuII / (p.K_Cu + CuII);

% ---- enzyme: only if deliberately carried over from Stage 2 ----
if p.carry_enzyme
    v_MM = p.k_cat * p.E3 * S4 / (p.Km + S4);
else
    v_MM = 0;                                    % NO enzyme in the leach vessel
end

% ---- homogeneous copper redox ----
v3 = p.k3 * CuII * S2;        % parasitic: 2Cu(II)+2S2O3 -> 2Cu(I)+S4O6
v4 = p.k4 * O2   * CuI;       % re-oxidation: 4Cu(I)+O2 -> 4Cu(II)

% ---- gold surface (thin film: constant area until exhausted) ----
A_Au    = p.A_Au0 * smooth_step(nAu, 1e-4*p.nAu0);
R_Au_O2 = p.k_Au_O2 * A_Au * fO2 * fS;           % umol min^-1
R_Au_Cu = 0;
if useCuII
    R_Au_Cu = p.k_Au_Cu * A_Au * fS * fCu;
end
R_Au = R_Au_O2 + R_Au_Cu;

% ---- copper surface (shrinking particle) ----
A_Cu = p.A_Cu0 * (nCu/p.nCu0)^(2/3) * smooth_step(nCu, 1e-4*p.nCu0);
v1A  = p.k_Cu_O2 * A_Cu * fO2 * fS;              % O2 route,   umol min^-1
v1B  = 0;
if useCuII
    v1B = p.k_Cu_Cu * A_Cu * fS * fCu;           % comproportionation
end
R_Cu = v1A + v1B;

% ---- balances ----
% Tetrathionate: produced by the parasitic reaction, consumed only if the
% enzyme was carried over.  Otherwise it is a DEAD-END product.
dS4 = -v_MM + p.k1 * CuII * S2;

% Thiosulfate: NO production term unless enzyme carried over.  This is the
% single most important structural difference from the simultaneous model.
dS2 = p.Y*v_MM ...
      - 2*v3 ...                 % 2 S2O3 per parasitic extent
      - (2/V)*R_Au ...           % 2 S2O3 per Au dissolved
      - (2/V)*v1A ...            % 2 S2O3 per Cu, O2 route
      - (4/V)*v1B;               % 4 S2O3 per Cu, comproportionation

dCuI  = (v1A + 2*v1B)/V + R_Au_Cu/V + 2*v3 - 4*v4;
dCuII = 4*v4 - v1B/V - R_Au_Cu/V - 2*v3;

dnAu  = -R_Au;
dAuC  = +R_Au/V;
dnCu  = -R_Cu;

% ---- alkalinity: OH- released by the O2-driven steps, minus the 2 H+
%      released per tetrathionate hydrolysed (only if enzyme carried over)
if p.pH_on
    dAlk = 4*v4 + R_Au_O2/V + v1A/V - 2*v_MM;   % umol L^-1 min^-1 of net OH-
else
    dAlk = 0;
end
pH = min(max(p.pH0 + Alk/p.beta, 0), 14);

dy = [dS4; dS2; dnAu; dAuC; dnCu; dCuI; dCuII; dAlk];

a = struct('R_Au',R_Au,'R_Au_O2',R_Au_O2,'R_Au_Cu',R_Au_Cu,'R_Cu',R_Cu, ...
           'A_Cu',A_Cu,'fS',fS,'fO2',fO2,'fCu',fCu,'v3',v3,'v4',v4, ...
           'v_MM',v_MM,'pH',pH,'Alk',Alk);
end


%% ===================================================================
%  HELPERS
%  ===================================================================
function s = smooth_step(x, w)
% Smooth 0->1 switch; keeps the solver happy when a solid runs out.
if x <= 0
    s = 0;
else
    s = x / (w + x);
end
end


function out = get_series(Y2, Y3, aux3, key)
% Pull a named series for the sweep plots.  Keys beginning '_2' come from
% Stage 2, everything else from Stage 3.
switch key
    case 'S2O3_2',       out = Y2(:,2);
    case 'S4O6_2',       out = Y2(:,1);
    case 'S2O3',         out = Y3(:,2);
    case 'S4O6',         out = Y3(:,1);
    case 'Au_recovery',  out = aux3.Au_recovery;
    case 'Cu_recovery',  out = aux3.Cu_recovery;
    case 'Au_dissolved', out = Y3(:,4);
    case 'CuI',          out = Y3(:,6);
    case 'CuII',         out = Y3(:,7);
    case 'R_Au',         out = aux3.R_Au;
    case 'fS',           out = aux3.fS;
    case 'pH',           out = aux3.pH;
    otherwise, error('get_series: unknown key "%s"', key);
end
end


function lab = label_for(key)
switch key
    case {'S2O3_2','S4O6_2','S2O3','S4O6','Au_dissolved','CuI','CuII'}
        lab = '\mumol L^{-1}';
    case {'Au_recovery','Cu_recovery'}, lab = 'recovery (%)';
    case {'R_Au'},                      lab = '\mumol min^{-1}';
    case {'fS'},                        lab = 'saturation factor (0-1)';
    case {'pH'},                        lab = 'pH';
    otherwise,                          lab = '';
end
end


function isS2 = is_stage2_key(key)
isS2 = numel(key) > 2 && strcmp(key(end-1:end), '_2');
end


