function print_summary(s1, t2, Y2, t3, Y3, aux3, p)
fprintf('\n=============== SEQUENTIAL MODEL SUMMARY ===============\n');

fprintf('\nSTAGE 1  culture / enzyme harvest\n');
fprintf('   [E] per litre of culture     %10.4g umol/L (%.0f molecules/cell)\n', ...
        s1.E_per_L, s1.molec_per_cell);
fprintf('   target [E] in Stage 2        %10.4g umol/L\n', p.E2);
fprintf('   culture volume required      %10.1f L per L of Stage 2\n', s1.culture_L);
fprintf('   purified TetH mass           %10.2f mg per L of Stage 2\n', s1.mass_mg);

fprintf('\nSTAGE 2  tetrathionate -> thiosulfate (closed, no copper)\n');
fprintf('   V_max = k_cat*[E]            %10.3f umol/L/min\n', p.k_cat*p.E2);
fprintf('   duration                     %10.1f h\n', p.t2/60);
fprintf('   S4O6  %8.0f -> %8.0f umol/L  (%.1f %% converted)\n', ...
        p.S4_0, Y2(end,1), 100*(1-Y2(end,1)/p.S4_0));
fprintf('   S2O3  %8.0f -> %8.0f umol/L  (%.1f mM product)\n', ...
        p.S2_0, Y2(end,2), Y2(end,2)/1000);
fprintf('   conservation check  S4+S2    %10.0f -> %.0f umol/L\n', ...
        p.S4_0+p.S2_0, Y2(end,1)+Y2(end,2));

fprintf('\nSTAGE 3  leaching (thiosulfate is a fixed budget)\n');
fprintf('   charged with                 %10.0f umol/L S2O3 (%.1f mM)\n', ...
        aux3.S2_charge, aux3.S2_charge/1000);
[~,iP] = max(aux3.R_Au);
fprintf('   peak gold rate               %10.4f umol/min at %.1f h\n', ...
        aux3.R_Au(iP), t3(iP)/60);
fprintf('      split at peak             %6.0f %% O2, %.0f %% Cu(II)\n', ...
        100*aux3.R_Au_O2(iP)/max(aux3.R_Au(iP),1e-30), ...
        100*aux3.R_Au_Cu(iP)/max(aux3.R_Au(iP),1e-30));
[~,iC] = max(Y3(:,6));
fprintf('   Cu(I) peak                   %10.0f umol/L at %.1f h\n', Y3(iC,6), t3(iC)/60);
fprintf('   Cu(II) final                 %10.0f umol/L\n', Y3(end,7));
fprintf('   gold recovery                %10.2f %%\n', aux3.Au_recovery(end));
fprintf('   copper dissolved             %10.4f %%\n', aux3.Cu_recovery(end));
fprintf('   final pH                     %10.2f\n', aux3.pH(end));

% where did the thiosulfate go?
dS2  = aux3.S2_charge - Y3(end,2);
gold = 2*Y3(end,4);
para = 2*(Y3(end,1) - Y3(1,1));
fprintf('\n   THIOSULFATE BUDGET (Stage 3)\n');
fprintf('      total consumed            %10.0f umol/L\n', dS2);
fprintf('      -> gold leaching          %10.1f umol/L (%.3f %%)\n', gold, 100*gold/max(dS2,1e-9));
fprintf('      -> parasitic Cu(II)       %10.0f umol/L (%.1f %%)\n', para, 100*para/max(dS2,1e-9));

fprintf('\n   TOTAL PROCESS TIME           %10.1f days (Stage 2 + Stage 3)\n', (p.t2+p.t3)/1440);
fprintf('========================================================\n\n');
end


%% ===================================================================
%  SWEEP  -  vary one parameter, re-running BOTH stages
%  ===================================================================
function sweep(p_base, field, values, plot_key)
figure('Name',sprintf('Sweep: %s',field),'Color','w','Position',[120 120 640 400]);
hold on;
leg = cell(1,numel(values));
for i = 1:numel(values)
    p = p_base;
    p.(field) = values(i);
    p = refresh(p);

    [t2, Y2, ~]    = run_stage2(p);
    [t3, Y3, aux3] = run_stage3(p, Y2(end,1), Y2(end,2));

    if is_stage2_key(plot_key)
        tt = t2; yy = get_series(Y2, Y3, aux3, plot_key);
    else
        tt = t3; yy = get_series(Y2, Y3, aux3, plot_key);
    end
    plot(tt/60, yy, 'LineWidth', 1.6);
    leg{i} = sprintf('%s = %g', field, values(i));
end
grid on; xlabel('time (h)'); ylabel(label_for(plot_key));
if is_stage2_key(plot_key)
    title(sprintf('STAGE 2:  %s vs %s', plot_key, field), 'Interpreter','none');
else
    title(sprintf('STAGE 3:  %s vs %s', plot_key, field), 'Interpreter','none');
end
legend(leg, 'Location','best','Interpreter','none');
hold off;
end


%% ===================================================================
%  CARRY-OVER COMPARISON
%  ===================================================================
function compare_carryover(p_base)
% Does transferring the enzyme with the liquor into Stage 3 help?
% If it does, the enzyme recycles parasitically-regenerated S4O6 back to S2O3.
figure('Name','Enzyme carry-over','Color','w','Position',[160 160 900 380]);

for k = 1:2
    p = p_base;
    p.carry_enzyme = (k == 2);
    p = refresh(p);
    [~, Y2, ~]     = run_stage2(p);
    [t3, Y3, aux3] = run_stage3(p, Y2(end,1), Y2(end,2));

    subplot(1,2,1); plot(t3/60, Y3(:,2), 'LineWidth', 1.6); hold on;
    subplot(1,2,2); plot(t3/60, aux3.Au_recovery, 'LineWidth', 1.6); hold on;

    fprintf('   carry_enzyme = %-5s ->  Au %.2f %%,  S2O3 left %.0f umol/L\n', ...
            mat2str(p.carry_enzyme), aux3.Au_recovery(end), Y3(end,2));
end

subplot(1,2,1); grid on; xlabel('time (h)'); ylabel('[S_2O_3^{2-}] (\mumol L^{-1})');
legend('enzyme left behind','enzyme carried over','Location','best');
title('Thiosulfate');
subplot(1,2,2); grid on; xlabel('time (h)'); ylabel('Au recovery (%)');
legend('enzyme left behind','enzyme carried over','Location','best');
title('Gold recovery');
if exist('sgtitle','file')
    sgtitle('Does carrying the enzyme into Stage 3 help?','FontWeight','bold');
end
end
