"""Generate the Software page's tables from the console's own inventory.

The wiki must not restate what the console monitors, because a restatement
drifts. This reads the same two files the console reads,

    dashboard-prototype/sensors.yaml    channels, actuators, vessels
    dashboard-prototype/stage_ph.yaml   per-stage set points and their status

and writes one TypeScript module into the wiki repository:

    ashesighana/src/contents/software-data.ts

TARGET IS A DIFFERENT REPOSITORY, the same one docs/make_wiki_dashboard.py
writes to. iGEM requires that repository to hold every coding asset the wiki
serves, so the generated module is committed there.

Regenerate with:  python docs/make_software_data.py
"""
import json
import pathlib

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
WIKI = ROOT.parent / "ashesighana"
PROTO = ROOT / "dashboard-prototype"
OUT = WIKI / "src" / "contents" / "software-data.ts"

# How a channel's data source reads on the page. `model` means the console is
# fed by an exported model trajectory, because no probe is attached yet.
FEED = {
    "model": "Model trajectory",
    "none": "Awaiting a sensor",
}

# How a stage's pH target reads. The words are the page's; the keys are
# stage_ph.yaml's own status values, so a new status fails loudly here rather
# than appearing as a blank cell on the wiki.
STATUS = {
    "measured_optimum": "Measured optimum",
    "operating_choice": "Operating choice",
    "analogue_only": "Analogue only",
    "organism_requirement": "Organism requirement",
    "undetermined": "Undetermined",
}


def ts(value, indent=2):
    """JSON is valid TypeScript for these shapes, and it quotes nothing wrong."""
    return json.dumps(value, indent=indent, ensure_ascii=True)


def target_of(stage):
    if stage["pH_set"] is not None:
        return "pH %.1f" % stage["pH_set"]
    if stage["pH_floor"] is not None:
        return "pH %.1f to %.1f" % (stage["pH_floor"], stage["pH_ceiling"])
    return "None recorded"


def build():
    if not WIKI.exists():
        raise SystemExit("wiki repository not found beside this one: %s" % WIKI)
    sensors = yaml.safe_load((PROTO / "sensors.yaml").read_text(encoding="utf-8"))
    stages = yaml.safe_load((PROTO / "stage_ph.yaml").read_text(encoding="utf-8"))
    by_key = {s["key"]: s for s in stages["stages"]}

    channels = []
    for c in sensors["channels"]:
        if c["feed"] not in FEED:
            raise SystemExit("unknown feed %r on channel %s" % (c["feed"], c["key"]))
        channels.append({
            "name": c["name"],
            "device": c["device"],
            "unit": c["unit"] or "-",
            "kind": c["kind"],
            "feed": FEED[c["feed"]],
            "live": c["feed"] != "none",
        })

    vessels = []
    for v in sensors["vessels"]:
        # The target shown is the first stage in the vessel that records one.
        target, status = "None recorded", None
        for k in v["stages"]:
            s = by_key[k]
            if s["pH_set"] is not None or s["pH_floor"] is not None:
                target, status = target_of(s), s["status"]
                break
        if status is not None and status not in STATUS:
            raise SystemExit("unknown status %r in vessel %s" % (status, v["key"]))
        # A vessel is dosed only if it has BOTH a target and a data path.
        # V1 and V4 record a set point but carry feed: none, and the console
        # shows their pumps as "not connected" for exactly that reason. The
        # page has to say the same thing or it describes software that does
        # not exist (AGENTS.md section 11 rule 5).
        dosed = status is not None and v["feed"] != "none"
        vessels.append({
            "key": v["key"],
            "name": v["name"],
            "stages": [by_key[k]["name"] for k in v["stages"]],
            "target": target,
            "evidence": STATUS[status] if status else "None recorded",
            "aerated": v["air_pump"] is True,
            "dosed": dosed,
            "pump": "connected" if dosed else "not connected",
        })

    rows = []
    for s in sorted(stages["stages"], key=lambda s: s["index"]):
        rows.append({
            "index": s["index"],
            "name": s["name"],
            "vessel": s["vessel"],
            "target": target_of(s),
            "evidence": STATUS[s["status"]],
            "runnable": bool(s["runnable"]),
        })

    limits = [{"name": n["name"], "why": " ".join(n["why"].split())}
              for n in sensors["not_measurable"]]

    actuators = [{"name": a["name"],
                  "rates": a["rates"],
                  "stopsOnInterlock": bool(a["stops_on_interlock"])}
                 for a in sensors["actuators"]]

    body = '''// GENERATED by docs/make_software_data.py in the modelling repository,
// from dashboard-prototype/sensors.yaml and dashboard-prototype/stage_ph.yaml.
// Do not edit. Edit the YAML, then regenerate.
//
// The console reads those same two files, so the tables on the Software page
// cannot drift from the software they describe.

export interface Channel {
  name: string
  device: string
  unit: string
  kind: string
  feed: string
  live: boolean
}

export interface Vessel {
  key: string
  name: string
  stages: string[]
  target: string
  evidence: string
  aerated: boolean
  dosed: boolean
  /** What the console's Equipment panel shows for this vessel's pump. */
  pump: string
}

export interface Stage {
  index: number
  name: string
  vessel: string
  target: string
  evidence: string
  runnable: boolean
}

export interface Limit {
  name: string
  why: string
}

export interface Actuator {
  name: string
  rates: number[]
  stopsOnInterlock: boolean
}

export const CHANNELS: Channel[] = %(channels)s

export const VESSELS: Vessel[] = %(vessels)s

export const STAGES: Stage[] = %(stages)s

export const NOT_MEASURABLE: Limit[] = %(limits)s

export const ACTUATORS: Actuator[] = %(actuators)s

/** Counts the page quotes in prose, so a sentence cannot fall out of step. */
export const COUNTS = {
  channels: CHANNELS.length,
  channelsLive: CHANNELS.filter((c) => c.live).length,
  vessels: VESSELS.length,
  vesselsDosed: VESSELS.filter((v) => v.dosed).length,
  stages: STAGES.length,
  stagesRunnable: STAGES.filter((s) => s.runnable).length,
  notMeasurable: NOT_MEASURABLE.length,
}
''' % {"channels": ts(channels), "vessels": ts(vessels), "stages": ts(rows),
       "limits": ts(limits), "actuators": ts(actuators)}

    bad = [n for n, line in enumerate(body.splitlines(), 1)
           if any(ord(c) > 127 for c in line)]
    if bad:
        raise SystemExit("non-ascii characters on lines %s" % bad[:5])

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(body, encoding="utf-8")
    print("wrote %s" % OUT)
    print("  channels      : %d, %d with a feed"
          % (len(channels), sum(1 for c in channels if c["live"])))
    print("  vessels       : %d, %d dosed"
          % (len(vessels), sum(1 for v in vessels if v["dosed"])))
    print("  stages        : %d, %d runnable"
          % (len(rows), sum(1 for r in rows if r["runnable"])))
    print("  not measurable: %d" % len(limits))
    print("  actuators     : %d" % len(actuators))


if __name__ == "__main__":
    build()
