"""Generate the wiki's software tables from the dashboard's own inventory.

The wiki must not restate what the dashboard monitors, because a restatement
drifts. These tables are built from the same two files the dashboard reads:

    dashboard-prototype/sensors.yaml    channels, actuators, vessels
    dashboard-prototype/stage_ph.yaml   per-stage set points and their status

Writes one HTML fragment, which docs/insert_software_section.py places into
wiki-prototype/index.html. Regenerate with:

    python docs/make_software_tables.py
"""
import pathlib

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
PROTO = ROOT / "dashboard-prototype"
OUT = ROOT / "docs" / "media" / "wiki" / "software_tables.html"

# The wiki's evidence pill classes, reused so the software section reads like
# every other section. See wiki-prototype/styles.css .evidence.
PILL = {
    "model": ("derived", "Model feed"),
    "none": ("needed", "Awaiting sensor"),
}
STATUS_PILL = {
    "measured_optimum": ("literature", "Measured"),
    "operating_choice": ("design", "Operating choice"),
    "analogue_only": ("proxy", "Analogue only"),
    "organism_requirement": ("needed", "Organism unchosen"),
    "undetermined": ("needed", "Undetermined"),
}


def esc(s):
    return (str(s).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"))


def channel_rows(sensors):
    out = []
    for c in sensors["channels"]:
        cls, label = PILL[c["feed"]]
        unit = c["unit"] if c["unit"] else "—"
        out.append(
            "                <tr><td>%s</td><td>%s</td><td>%s</td>"
            "<td><span class=\"evidence %s\">%s</span></td></tr>"
            % (esc(c["name"]), esc(c["device"]), esc(unit), cls, label))
    return out


def vessel_rows(sensors, stages):
    by_key = {s["key"]: s for s in stages["stages"]}
    out = []
    for v in sensors["vessels"]:
        names = ", ".join(esc(by_key[k]["name"]) for k in v["stages"])
        # the set point shown is the first stage in the vessel that records one
        sp, status = None, None
        for k in v["stages"]:
            s = by_key[k]
            if s["pH_set"] is not None or s["pH_floor"] is not None:
                sp = ("pH %.1f" % s["pH_set"] if s["pH_set"] is not None
                      else "%.1f – %.1f" % (s["pH_floor"], s["pH_ceiling"]))
                status = s["status"]
                break
        cls, label = STATUS_PILL.get(status, ("needed", "None recorded"))
        air = "Yes" if v["air_pump"] is True else "Not decided"
        out.append(
            "                <tr><td>%s</td><td>%s</td><td>%s</td><td>%s</td>"
            "<td><span class=\"evidence %s\">%s</span></td></tr>"
            % (esc(v["key"]), names, esc(sp or "—"), air, cls, label))
    return out


def not_measurable_rows(sensors):
    return ["                <tr><td>%s</td><td>%s</td></tr>"
            % (esc(n["name"]), esc(n["why"])) for n in sensors["not_measurable"]]


def build():
    sensors = yaml.safe_load((PROTO / "sensors.yaml").read_text(encoding="utf-8"))
    stages = yaml.safe_load((PROTO / "stage_ph.yaml").read_text(encoding="utf-8"))

    live = sum(1 for c in sensors["channels"] if c["feed"] != "none")
    parts = [
        "<!-- GENERATED by docs/make_software_tables.py. Do not edit. -->",
        "<table class=\"parameter-table software-table\">",
        "  <colgroup><col><col><col><col></colgroup>",
        "  <thead><tr><th>Channel</th><th>Instrument</th><th>Unit</th>"
        "<th>Data today</th></tr></thead>",
        "  <tbody>",
    ]
    parts += channel_rows(sensors)
    parts += ["  </tbody>", "</table>"]

    parts += [
        "<table class=\"parameter-table software-table\">",
        "  <colgroup><col><col><col><col><col></colgroup>",
        "  <thead><tr><th>Vessel</th><th>Stage</th><th>pH target</th>"
        "<th>Aerated</th><th>Target evidence</th></tr></thead>",
        "  <tbody>",
    ]
    parts += vessel_rows(sensors, stages)
    parts += ["  </tbody>", "</table>"]

    parts += [
        "<table class=\"parameter-table software-table\">",
        "  <colgroup><col><col></colgroup>",
        "  <thead><tr><th>Quantity</th><th>Why no instrument reads it</th></tr></thead>",
        "  <tbody>",
    ]
    parts += not_measurable_rows(sensors)
    parts += ["  </tbody>", "</table>"]

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(parts) + "\n", encoding="utf-8")
    print("wrote %s" % OUT.relative_to(ROOT))
    print("  channels      : %d, %d with a feed" % (len(sensors["channels"]), live))
    print("  vessels       : %d" % len(sensors["vessels"]))
    print("  not measurable: %d" % len(sensors["not_measurable"]))


if __name__ == "__main__":
    build()
