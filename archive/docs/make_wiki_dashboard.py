"""Generate the wiki's copy of the bioreactor dashboard.

The dashboard is authored once, in dashboard-prototype/index.html. The team
wiki needs the same page in the wiki's own palette and typefaces, as a
standalone document a visitor opens in a new tab. This script produces that
copy so nobody maintains two files that drift.

TARGET IS A DIFFERENT REPOSITORY. The wiki is

    https://gitlab.igem.org/2026/ashesighana

checked out beside this one. iGEM requires that repository to contain every
coding asset it serves, so the generated page, its data and its font files are
committed there, not fetched from here at build time.

WHAT IT CHANGES, and nothing else:

1. The colour tokens become the wiki's, from src/styles/tokens.css.
2. The four typefaces become the wiki's, in the wiki's own roles:
     Fraunces   display, the wordmark
     DM Sans    body
     Playfair   small uppercase labels, the wiki's --font-mono
     DM Mono    every readout, the wiki's --font-code
   DM Sans and DM Mono load from static.igem.wiki, where the wiki already
   loads them. Fraunces and Playfair are bundled in the wiki's src/assets and
   hashed by Vite, so a page in public/ cannot reach them; their latin woff2
   files are copied beside the page instead. Nothing loads from a third-party
   CDN, which iGEM forbids.
3. The two dark-mode blocks are dropped. The wiki is light only.
4. Nothing is added: the source page carries the wiki's own header, which
   this script checks for.

Regenerate with:  python docs/make_wiki_dashboard.py
"""
import pathlib
import re
import shutil

ROOT = pathlib.Path(__file__).resolve().parent.parent
WIKI = ROOT.parent / "ashesighana"
SRC = ROOT / "dashboard-prototype" / "index.html"
OUT = WIKI / "public" / "dashboard"

FONT_HOST = "https://static.igem.wiki/teams/6321/wiki/fonts"

# Copied beside the page because Vite hashes them out of reach in src/assets.
# Latin only: the dashboard is ASCII, enforced at the foot of this script.
BUNDLED = ["fraunces-var-latin.woff2", "playfair-var-latin.woff2"]

# ---------------------------------------------------------------------------
# Every value below is the wiki's own, from ashesighana/src/styles/tokens.css.
# Contrast is measured against the page ground #f8f4ea:
#
#   --color-void       #1c150c  16.45:1   body text
#   --color-char       #3d3323  11.02:1   secondary text
#   --color-oxide-dark #6f6151   5.46:1   muted text
#   --color-bio        #3f6f4a   5.33:1   healthy
#   --color-copper-dark#966214   4.72:1   accent text
#   --color-toxic      #bf4a2b   4.52:1   alarm
#
# Two of the wiki's tokens are deliberately NOT used as text:
#   --color-copper #c0801f  3.01:1  large text only, so it stays on fills
#   --color-oxide  #a89b86  2.48:1  fails at every size
#
# The wiki carries no amber, so --warn takes copper-dark alongside --accent.
# They do not co-occur: --accent marks the dosing figure, --warn marks an
# assumption tag and an operator stop.
HEAD = """<link rel="preconnect" href="https://static.igem.wiki" crossorigin>
<style>
  /* Wiki typefaces. DM Sans and DM Mono from iGEM static hosting, where the
     wiki already loads them. Fraunces and Playfair beside this page. */
  @font-face {
    font-family: 'DM Sans'; font-style: normal; font-weight: 400;
    font-display: swap; src: url('%(host)s/dm-sans-400.woff2') format('woff2');
  }
  @font-face {
    font-family: 'DM Sans'; font-style: normal; font-weight: 500;
    font-display: swap; src: url('%(host)s/dm-sans-500.woff2') format('woff2');
  }
  @font-face {
    font-family: 'DM Sans'; font-style: normal; font-weight: 600;
    font-display: swap; src: url('%(host)s/dm-sans-600.woff2') format('woff2');
  }
  @font-face {
    font-family: 'DM Mono'; font-style: normal; font-weight: 400;
    font-display: swap; src: url('%(host)s/dm-mono-400.woff2') format('woff2');
  }
  @font-face {
    font-family: 'DM Mono'; font-style: normal; font-weight: 500;
    font-display: swap; src: url('%(host)s/dm-mono-500.woff2') format('woff2');
  }
  @font-face {
    font-family: 'Fraunces'; font-style: normal; font-weight: 100 900;
    font-display: swap; src: url('fonts/fraunces-var-latin.woff2') format('woff2');
  }
  @font-face {
    font-family: 'Playfair'; font-style: normal; font-weight: 100 900;
    font-display: swap; src: url('fonts/playfair-var-latin.woff2') format('woff2');
  }
</style>

<style>
""" % {"host": FONT_HOST}

TOKENS = """  :root {
    /* Wiki palette and typefaces. Values from ashesighana/src/styles/
       tokens.css. GENERATED by docs/make_wiki_dashboard.py, do not edit. */
    --bg:        #F8F4EA;   /* --surface-page, --ground-clear */
    --raise:     #FFFFFF;   /* chrome white, a step above the ground */
    --ink:       #1C150C;   /* --color-void       */
    --ink-2:     #3D3323;   /* --color-char       */
    --muted:     #6F6151;   /* --color-oxide-dark */
    --hair:      #E6D9BF;   /* --surface-line     */
    --hair-2:    #EFE6D4;   /* --surface-soft     */
    --accent:    #966214;   /* --color-copper-dark */
    --accent-bg: #FAF1DC;   /* --color-copper-pale */
    --ok:        #3F6F4A;   /* --color-bio        */
    --warn:      #966214;   /* --color-copper-dark */
    --crit:      #BF4A2B;   /* --color-toxic      */
    --ok-bg:     #EAF1E7;   /* --color-bio-pale   */
    --warn-bg:   #FAF1DC;   /* --color-copper-pale */
    --crit-bg:   #F6DDD3;   /* --color-toxic-light */

    /* Four faces, in the wiki's roles. See tokens.css --font-*. */
    --font:         'DM Sans', system-ui, sans-serif;
    --font-display: 'Fraunces', Georgia, serif;
    --font-label:   'Playfair', Georgia, serif;
    --font-num:     'DM Mono', 'Courier New', monospace;

    /* one scale. Every size on the page is one of these */
    --t-micro: 10px;
    --t-tick:  11px;
    --t-small: 12px;
    --t-body:  13px;
    --t-num-m: 20px;
    --t-num-l: 30px;
    --t-hero:  48px;

    --gut: 24px;
    --r: 12px;

    /* --shadow-card and --color-text-on-light. The page ground is the wiki's
       #f8f4ea and every panel is white, so the shadow is what separates
       them. --ink-nav is the header's link colour. */
    --shadow: 0 12px 32px rgba(18, 20, 11, 0.08);
    --ink-nav: #2A2013;
  }
"""

# Face assignments. The dashboard was authored with one family everywhere;
# the wiki uses four, so the rules that carry a different role are retargeted.
FACES = [
    # every readout, so digits hold their width as values change
    ("  .stat b, .prog .lb, .read b, .split .row b,\n"
     "  .f input, .f select, td.n, .log time, pre.csv, .repstat b {\n"
     "    font-variant-numeric: tabular-nums;\n"
     "    font-feature-settings: \"tnum\" 1;\n"
     "  }",
     "  .stat b, .prog .lb, .read b, .split .row b,\n"
     "  .f input, .f select, td.n, .log time, pre.csv, .repstat b,\n"
     "  .headline .n, .kv .row b {\n"
     "    font-family: var(--font-num);\n"
     "    font-variant-numeric: tabular-nums;\n"
     "    font-feature-settings: \"tnum\" 1;\n"
     "  }"),
    # the wiki's small uppercase label face
    ("  .lab, .stat u, .read u, .f > u, .sect, .key, .repstat u {\n"
     "    font-size: var(--t-micro);",
     "  .lab, .stat u, .read u, .f > u, .sect, .key, .repstat u, th {\n"
     "    font-family: var(--font-label);\n"
     "    font-size: var(--t-micro);"),
    # the wordmark takes the display face
    ("  .mark { margin-right: auto; font-size: var(--t-body); font-weight: 600;",
     "  .mark { margin-right: auto; font-family: var(--font-display);\n"
     "          font-size: var(--t-body); font-weight: 600;"),
]

def build():
    if not WIKI.exists():
        raise SystemExit("wiki repository not found beside this one: %s" % WIKI)
    t = SRC.read_text(encoding="utf-8")

    # 1. the Google Fonts link is a third-party CDN; iGEM forbids it
    link = ('<link rel="stylesheet" '
            'href="https://fonts.googleapis.com/css2'
            '?family=Poppins:wght@300;400;500;600&display=swap">\n\n<style>\n')
    if link not in t:
        raise SystemExit("font link not found; the dashboard head has changed")
    t = t.replace(link, HEAD, 1)

    # 2. tokens, and 3. the two dark blocks, in one span
    start = t.index("  :root {")
    end = t.index("  * { box-sizing: border-box; }")
    t = t[:start] + TOKENS + "\n" + t[end:]

    for old, new in FACES:
        if old not in t:
            raise SystemExit("face rule not found:\n%s" % old.splitlines()[0])
        t = t.replace(old, new, 1)

    # 4. the page carries the wiki's own header, so it needs no back link.
    #    Confirm the header is there rather than assume it.
    if 'class="wnav"' not in t:
        raise SystemExit("the wiki header is missing from the source page")

    t = t.replace(
        "<title>Gold Leach Console</title>",
        "<title>Gold Leach Console</title>\n"
        "<!-- GENERATED by docs/make_wiki_dashboard.py in the modelling\n"
        "     repository, from dashboard-prototype/index.html.\n"
        "     Do not edit this file. Edit the source, then regenerate. -->", 1)

    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "fonts").mkdir(exist_ok=True)
    (OUT / "index.html").write_text(t, encoding="utf-8")
    shutil.copyfile(ROOT / "dashboard-prototype" / "runs.js", OUT / "runs.js")
    for f in BUNDLED:
        shutil.copyfile(WIKI / "src" / "assets" / "fonts" / f, OUT / "fonts" / f)

    bad = [n for n, line in enumerate(t.splitlines(), 1)
           if any(ord(c) > 127 for c in line)]
    hosts = set(re.findall(r"https?://([A-Za-z0-9.-]+)", t))

    print("wrote %s  %.1f kB  %d lines"
          % (OUT / "index.html", len(t.encode("utf-8")) / 1000, len(t.splitlines())))
    print("  runs.js  %.1f kB" % ((OUT / "runs.js").stat().st_size / 1000))
    for f in BUNDLED:
        print("  fonts/%s  %.1f kB" % (f, (OUT / "fonts" / f).stat().st_size / 1000))
    print("  non-ascii lines : %d" % len(bad))
    print("  external hosts  : %s" % (sorted(hosts) or "none"))
    if hosts - {"static.igem.wiki"}:
        raise SystemExit("a third-party host survived; iGEM forbids these")
    if bad:
        raise SystemExit("non-ascii characters survived")


if __name__ == "__main__":
    build()
